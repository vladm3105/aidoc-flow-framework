"""Unit tests for sdd_doc_lint.observability_adapter (CHG-108).

Validates:
1. Markdown specification sheet projection with read-only generator banner.
2. Pure-text Mermaid diagram generation (Lineage DAG and C4 Container views).
3. Traceability verification compliance matrix table projection.
4. PR impact and visual delta projection for CI/CD automation.
"""

from __future__ import annotations

import unittest

from sdd_doc_lint.graph_engine import SddGraph
from sdd_doc_lint.observability_adapter import ObservabilityAdapter


class TestObservabilityAdapter(unittest.TestCase):
    def setUp(self) -> None:
        self.adapter = ObservabilityAdapter()

    def _sample_graph(self) -> SddGraph:
        g = SddGraph()
        g.slice_ids.add("INIT-01_auth_token")

        # Business Objective (BRD)
        g.add_node(
            {
                "id": "BRD.01.01.a1b2",
                "type": "business_objective",
                "title": "Secure Session Management",
                "statement": "Protect user accounts against token replay attacks.",
                "properties": {"priority": "P0", "roi_target": "Zero session breaches"},
            }
        )

        # Product Capability (PRD)
        g.add_node(
            {
                "id": "PRD.02.01.c3d4",
                "type": "product_capability",
                "title": "Short-lived Access Tokens",
                "statement": "Issue JWTs with 15-minute expiration time.",
                "properties": {"persona": "API Consumer"},
            }
        )

        # Formal Requirement (EARS)
        g.add_node(
            {
                "id": "EARS.03.01.e5f6",
                "type": "formal_requirement",
                "title": "Token Expiration Invariant",
                "statement": "When a token expires, the system shall reject requests with 401.",
                "pattern": "event_driven",
            }
        )

        # Acceptance Scenario (BDD)
        g.add_node(
            {
                "id": "BDD.04.01.g7h8",
                "type": "acceptance_scenario",
                "title": "Expired Token Rejection",
                "given": "an access token expired 1 minute ago",
                "when": "the client sends a GET /api/v1/profile request",
                "then": "the server returns HTTP 401 Unauthorized",
            }
        )

        # Architectural Decision (ADR)
        g.add_node(
            {
                "id": "ADR.05.01.i9j0",
                "type": "architectural_decision",
                "title": "Asymmetric JWT Signing",
                "status": "Accepted",
                "context": "Need decentralized signature verification across services.",
                "decision": "Adopt RS256 with rotating public keys.",
                "consequences": "Minor CPU overhead on signature verification.",
            }
        )

        # Test Fixture (TDD)
        g.add_node(
            {
                "id": "TDD.07.01.k1l2",
                "type": "test_fixture",
                "title": "Test Expired Token Handling",
                "target_file": "tests/test_jwt_auth.py",
                "command": "pytest -v tests/test_jwt_auth.py",
            }
        )

        # Task Action (IPLAN)
        g.add_node(
            {
                "id": "TASK.08.01.m3n4",
                "type": "task_action",
                "title": "Implement JWT Middleware",
                "action": "edit",
                "target_file": "src/auth/jwt.py",
            }
        )

        # Edges
        g.add_edge("BRD.01.01.a1b2", "PRD.02.01.c3d4", "decomposes_to")
        g.add_edge("PRD.02.01.c3d4", "EARS.03.01.e5f6", "realizes")
        g.add_edge("BDD.04.01.g7h8", "EARS.03.01.e5f6", "verifies")
        g.add_edge("TDD.07.01.k1l2", "BDD.04.01.g7h8", "proves")
        g.add_edge("ADR.05.01.i9j0", "EARS.03.01.e5f6", "constrains")
        g.add_edge("TASK.08.01.m3n4", "EARS.03.01.e5f6", "implements")

        return g

    def test_render_spec_sheet(self) -> None:
        """Verify complete Markdown spec sheet rendering with banner and section headers."""
        g = self._sample_graph()
        output = self.adapter.render_spec_sheet(g)

        # 1. Generator banner is present
        self.assertIn("GENERATED BY SDD-RENDER", output)
        self.assertIn("DO NOT EDIT DIRECTLY", output)

        # 2. Main sections are present
        self.assertIn("# Specification: INIT-01_auth_token", output)
        self.assertIn("## 1. Business Objectives & Strategic Intent", output)
        self.assertIn("Secure Session Management (`BRD.01.01.a1b2`)", output)
        self.assertIn("## 2. Product Scope & Container Capabilities", output)
        self.assertIn("Short-lived Access Tokens (`PRD.02.01.c3d4`)", output)
        self.assertIn("## 3. Formal Functional Requirements (EARS)", output)
        self.assertIn("- **`EARS.03.01.e5f6`** [EVENT_DRIVEN]:", output)
        self.assertIn("## 4. Acceptance Scenarios & Behavioral Oracles (BDD)", output)
        self.assertIn("- **Given** an access token expired 1 minute ago", output)
        self.assertIn("- **When** the client sends a GET /api/v1/profile request", output)
        self.assertIn("- **Then** the server returns HTTP 401 Unauthorized", output)
        self.assertIn("## 5. Architectural Decisions (ADR)", output)
        self.assertIn("Asymmetric JWT Signing (`ADR.05.01.i9j0`)", output)
        self.assertIn("- **Decision**: Adopt RS256 with rotating public keys.", output)
        self.assertIn("## 6. Implementation Tasks & Verification Proofs", output)
        self.assertIn("`pytest -v tests/test_jwt_auth.py`", output)
        self.assertIn("`TASK.08.01.m3n4`", output)

    def test_render_mermaid_lineage(self) -> None:
        """Verify Mermaid lineage diagram syntax and node/edge connections."""
        g = self._sample_graph()
        diagram = self.adapter.render_mermaid(g, diagram_type="lineage")

        self.assertTrue(diagram.startswith("```mermaid\ngraph LR\n"))
        self.assertIn('    BRD.01.01.a1b2["BRD.01.01.a1b2<br/>Secure Session Management"]', diagram)
        self.assertIn("    BRD.01.01.a1b2 -->|decomposes_to| PRD.02.01.c3d4", diagram)
        self.assertIn("    BDD.04.01.g7h8 -->|verifies| EARS.03.01.e5f6", diagram)
        self.assertIn("    TDD.07.01.k1l2 -->|proves| BDD.04.01.g7h8", diagram)
        self.assertTrue(diagram.endswith("```\n"))

    def test_render_mermaid_c4(self) -> None:
        """Verify Mermaid C4 Container view."""
        g = self._sample_graph()
        diagram = self.adapter.render_mermaid(g, diagram_type="c4-container")

        self.assertTrue(diagram.startswith("```mermaid\ngraph TB\n"))
        self.assertIn('subgraph Containers["System Containers"]', diagram)
        self.assertIn("PRD.02.01.c3d4", diagram)

    def test_render_matrix(self) -> None:
        """Verify traceability compliance matrix table generation."""
        g = self._sample_graph()
        matrix = self.adapter.render_matrix(g)

        self.assertIn("# Traceability Verification Matrix", matrix)
        self.assertIn("| Requirement (EARS) | BDD Oracle | Test Fixture (TDD) | Status |", matrix)
        self.assertIn(
            "| `EARS.03.01.e5f6` | `BDD.04.01.g7h8` | `TDD.07.01.k1l2` | ✅ PASS |", matrix
        )

    def test_render_pr_impact_summary(self) -> None:
        """Verify PR impact report with delta stats and visual delta graph."""
        g_base = self._sample_graph()
        g_head = self._sample_graph()

        # Add a new requirement and task in head
        g_head.add_node(
            {
                "id": "EARS.03.02.z9y8",
                "type": "formal_requirement",
                "title": "Refresh Token Rotation",
                "statement": "When a refresh token is used, the system shall issue a new one.",
            }
        )
        g_head.add_edge("PRD.02.01.c3d4", "EARS.03.02.z9y8", "realizes")

        report = self.adapter.render_pr_impact_summary(g_base, g_head)
        self.assertIn("### 📊 Native SDD Graph Impact Summary", report)
        self.assertIn("- **Added Nodes**: 1", report)
        self.assertIn("EARS.03.02.z9y8", report)
        self.assertIn("```mermaid", report)

    def test_render_spec_sheet_enriched_properties(self) -> None:
        """Verify projection of metadata problem context, rich node descriptions, and edge rationales."""
        g = SddGraph()
        g.slice_ids.add("PRD-01_checkout")
        g.metadata = {
            "description": "High-throughput checkout capability",
            "problem_statement": {
                "problem": "High checkout drop-off rate",
                "impact": "$1M annual revenue loss",
                "opportunity": "Capture repeat shopper loyalty",
                "current_state": ["18% mobile payment failure rate"],
            },
            "mvp_hypothesis": {
                "statement": "Users will repeat purchase with 1-click checkout",
                "validation": ">=30% 30-day repeat purchase rate",
            },
        }

        g.add_node(
            {
                "id": "PRD.02.04.a1b2",
                "type": "product_capability",
                "title": "Idempotent Order Gateway",
                "statement": "Processes batch orders with zero duplicate charges.",
                "description": "Enterprise order gateway implementing distributed lock deduplication.",
                "properties": {
                    "persona": "Merchant",
                    "priority": "P1-Must",
                    "sla_threshold": "p99 < 50ms",
                    "user_story": {
                        "role": "Registered Merchant",
                        "want": "submit batch orders",
                        "so_that": "duplicates are eliminated",
                    },
                    "acceptance_criteria": [
                        "Repeated idempotency key returns cached response",
                    ],
                    "interaction_steps": [
                        "Step 1: Client submits POST /orders",
                    ],
                    "edge_cases": [
                        "Network disconnect triggers automated reconciliation",
                    ],
                },
            }
        )

        g.add_node(
            {
                "id": "BRD.01.07.c3d4",
                "type": "business_objective",
                "title": "Order Settlement Capability",
                "statement": "Automates merchant settlement clearing.",
                "description": "Evaluates merchant account eligibility and commits ledger debits.",
                "properties": {"priority": "P0", "category": "business_capability"},
            }
        )

        g.add_node(
            {
                "id": "EVAL.10.01.e5f6",
                "type": "evaluation_suite",
                "title": "End-to-End Regression Gate",
                "statement": "Verifies 100% test fixture coverage and performance bounds.",
                "description": "Automated pipeline gate executing load benchmarks.",
                "properties": {
                    "quality_gate": "0 P0 failures allowed",
                    "benchmark_threshold": "p99 < 50ms under 5000 TPS",
                },
            }
        )

        # Enriched edge with description and rationale
        g.add_edge(
            "PRD.02.04.a1b2",
            "BRD.01.07.c3d4",
            "realizes",
            notes="Realizes merchant settlement",
            description="Exposes idempotent HTTP REST gateway to fulfill settlement.",
            rationale="Decouples ingress from banking delays.",
        )

        output = self.adapter.render_spec_sheet(g)

        # Verify metadata projection
        self.assertIn("## Executive Problem Context", output)
        self.assertIn("- **Problem Statement**: High checkout drop-off rate", output)
        self.assertIn("- **Business Impact**: $1M annual revenue loss", output)
        self.assertIn("- **Market Opportunity**: Capture repeat shopper loyalty", output)
        self.assertIn("18% mobile payment failure rate", output)
        self.assertIn("## Core MVP Hypothesis", output)
        self.assertIn("Users will repeat purchase with 1-click checkout", output)

        # Verify node description and rich properties
        self.assertIn(
            "Enterprise order gateway implementing distributed lock deduplication.", output
        )
        self.assertIn(
            "**User Story**: As a **Registered Merchant**, I want to **submit batch orders**, so that **duplicates are eliminated**.",
            output,
        )
        self.assertIn("Repeated idempotency key returns cached response", output)
        self.assertIn("Step 1: Client submits POST /orders", output)
        self.assertIn("Network disconnect triggers automated reconciliation", output)

        # Verify edge note, description, and rationale projection
        self.assertIn("Realizes merchant settlement", output)
        self.assertIn("*Rationale*: Decouples ingress from banking delays.", output)

        # Verify EVAL section
        self.assertIn("## 7. Evaluation Suites & Quality Gates (EVAL)", output)
        self.assertIn("End-to-End Regression Gate (`EVAL.10.01.e5f6`)", output)
        self.assertIn("0 P0 failures allowed", output)


if __name__ == "__main__":
    unittest.main()
